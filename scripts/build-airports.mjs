#!/usr/bin/env node
// Builds src/features/itinerary/data/airports.ts: coordinates for airports with scheduled flights,
// so flight legs stored as airport codes ("BLR → NRT") count towards trip distance. Bundled, so
// lookups never hit a server.
//
// Source: OurAirports (public domain), large and medium airports with an IATA code and scheduled service.
// Usage: node scripts/build-airports.mjs [path-to-airports.csv]

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const SOURCE_URL = "https://davidmegginson.github.io/ourairports-data/airports.csv";
const OUT = fileURLToPath(new URL("../src/features/itinerary/data/airports.ts", import.meta.url));

async function loadSource() {
  const path = process.argv[2];
  if (path) return readFile(path, "utf8");
  const response = await fetch(SOURCE_URL);
  if (!response.ok) throw new Error(`download failed: ${response.status}`);
  return response.text();
}

/** Minimal CSV parsing: quoted fields may contain commas and doubled quotes. */
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n") {
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else if (ch !== "\r") field += ch;
  }
  if (field || row.length) rows.push([...row, field]);
  return rows;
}

const [header, ...records] = parseCsv(await loadSource());
const col = (name) => header.indexOf(name);
const rows = records
  .filter((r) => /^[A-Z]{3}$/.test(r[col("iata_code")]) && ["large_airport", "medium_airport"].includes(r[col("type")]) && r[col("scheduled_service")] === "yes")
  .map((r) => [r[col("iata_code")], Number(r[col("latitude_deg")]).toFixed(2), Number(r[col("longitude_deg")]).toFixed(2), r[col("iso_country")]].join("|"))
  .sort();

const file = `// Generated by scripts/build-airports.mjs from OurAirports (public domain). Do not edit.
// Row format: IATA code|lat|lon|ISO country
export const AIRPORT_ROWS = ${JSON.stringify(rows.join("\n"))};
`;
await writeFile(OUT, file);
console.log(`${rows.length} airports, ${(file.length / 1024).toFixed(0)} KB`);
